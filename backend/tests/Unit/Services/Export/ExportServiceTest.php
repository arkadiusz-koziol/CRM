<?php

declare(strict_types=1);

namespace Tests\Unit\Services\Export;

use App\Config\ExportConfig;
use App\Services\Export\ExportService;
use App\Services\Export\Formatters\CsvFormatter;
use App\Services\Export\Formatters\PdfFormatter;
use App\Services\Export\Formatters\XlsxFormatter;
use Carbon\Carbon;
use Illuminate\Contracts\Filesystem\Filesystem;
use Illuminate\Http\Response;
use Illuminate\Support\Facades\Storage;
use Mockery;
use Psr\Log\LoggerInterface;
use Tests\TestCase;

class ExportServiceTest extends TestCase
{
    private ExportService $exportService;

    private CsvFormatter $csvFormatter;

    private XlsxFormatter $xlsxFormatter;

    private PdfFormatter $pdfFormatter;

    private LoggerInterface $logger;

    private Filesystem $storage;

    private ExportConfig $config;

    private Carbon $now;

    protected function setUp(): void
    {
        parent::setUp();

        $this->csvFormatter = Mockery::mock(CsvFormatter::class);
        $this->xlsxFormatter = Mockery::mock(XlsxFormatter::class);
        $this->pdfFormatter = Mockery::mock(PdfFormatter::class);
        $this->logger = Mockery::mock(LoggerInterface::class);
        $this->storage = Mockery::mock(Filesystem::class);
        $this->config = new ExportConfig(
            storagePath: 'exports',
            maxFileSize: 50 * 1024 * 1024,
            chunkSize: 1000,
            fileTtl: 7,
            logoPath: 'assets/logo.png',
            footerText: 'Generated by CRM System',
        );
        $this->now = Mockery::mock(Carbon::class);

        $this->exportService = new ExportService(
            $this->csvFormatter,
            $this->xlsxFormatter,
            $this->pdfFormatter,
            $this->logger,
            $this->storage
        );

        Storage::fake('local');
    }

    protected function tearDown(): void
    {
        Mockery::close();
        parent::tearDown();
    }

    public function test_export_to_csv_creates_file_and_returns_response(): void
    {
        $data = [
            ['name' => 'John Doe', 'email' => 'john@example.com'],
            ['name' => 'Jane Smith', 'email' => 'jane@example.com'],
        ];
        $filename = 'test_export';
        $headers = ['Name', 'Email'];
        $csvContent = "Name,Email\nJohn Doe,john@example.com\nJane Smith,jane@example.com\n";

        $this->csvFormatter
            ->expects('format')
            ->with($data, $headers)
            ->andReturn($csvContent);

        $this->logger
            ->expects('info')
            ->with('Starting CSV export', [
                'filename' => $filename,
                'record_count' => 2,
            ]);

        $this->storage
            ->expects('put')
            ->with('exports/test_export.csv', $csvContent);

        $this->storage
            ->expects('get')
            ->with('exports/test_export.csv')
            ->andReturn($csvContent);

        $this->logger
            ->expects('info')
            ->with('File stored successfully', [
                'path' => 'exports/test_export.csv',
                'size' => strlen($csvContent),
            ]);

        $response = $this->exportService->exportToCsv($data, $filename, $headers);

        $this->assertInstanceOf(Response::class, $response);
        $this->assertEquals('text/csv; charset=UTF-8', $response->headers->get('Content-Type'));
        $this->assertStringContainsString('attachment; filename="test_export.csv"', $response->headers->get('Content-Disposition'));
    }

