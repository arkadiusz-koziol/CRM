    public function test_export_with_chunking_handles_large_datasets(): void
    {
        $dataProvider = function (int $offset, int $limit) {
            if ($offset === 0) {
                return [
                    ['name' => 'John Doe', 'email' => 'john@example.com'],
                    ['name' => 'Jane Smith', 'email' => 'jane@example.com'],
                ];
            }

            return [];
        };

        $filename = 'chunked_export';
        $format = 'csv';
        $headers = ['Name', 'Email'];
        $csvContent = "Name,Email\nJohn Doe,john@example.com\nJane Smith,jane@example.com\n";

        $this->csvFormatter
            ->expects('format')
            ->with([
                ['name' => 'John Doe', 'email' => 'john@example.com'],
                ['name' => 'Jane Smith', 'email' => 'jane@example.com'],
            ], $headers)
            ->andReturn($csvContent);

        $this->logger
            ->expects('info')
            ->with('Starting chunked export', [
                'filename' => $filename,
                'format' => $format,
            ]);

        $this->logger
            ->expects('info')
            ->with('Starting CSV export', [
                'filename' => $filename,
                'record_count' => 2,
            ]);

        $this->storage
            ->expects('put')
            ->with('exports/chunked_export.csv', $csvContent);

        $this->storage
            ->expects('get')
            ->with('exports/chunked_export.csv')
            ->andReturn($csvContent);

        $this->logger
            ->expects('info')
            ->with('File stored successfully', [
                'path' => 'exports/chunked_export.csv',
                'size' => strlen($csvContent),
            ]);

        $response = $this->exportService->exportWithChunking($dataProvider, $filename, $format, $headers);

        $this->assertInstanceOf(Response::class, $response);
    }

    public function test_export_with_chunking_throws_exception_for_unsupported_format(): void
    {
        $dataProvider = function (int $offset, int $limit) {
            return [];
        };

        $this->logger
            ->expects('info')
            ->with('Starting chunked export', [
                'filename' => 'test',
                'format' => 'invalid',
            ]);

        $this->expectException(\App\Exceptions\Export\ExportGenerationException::class);
        $this->expectExceptionMessage('Failed to generate invalid export: Unsupported format');

        $this->exportService->exportWithChunking($dataProvider, 'test', 'invalid', []);
    }

    public function test_cleanup_old_files_removes_old_files(): void
    {
        $this->storage
            ->expects('files')
            ->with('exports')
            ->andReturn(['exports/old_file.csv', 'exports/new_file.csv']);

        $this->storage
            ->expects('lastModified')
            ->with('exports/old_file.csv')
            ->andReturn(now()->subDays(10)->timestamp);

        $this->storage
            ->expects('lastModified')
            ->with('exports/new_file.csv')
            ->andReturn(now()->subDays(1)->timestamp);

        $this->storage
            ->expects('delete')
            ->with('exports/old_file.csv');

        $this->logger
            ->expects('info')
            ->with('Cleaned up old export files', Mockery::type('array'));

        $deletedCount = $this->exportService->cleanupOldFiles();

        $this->assertIsInt($deletedCount);
    }
}
